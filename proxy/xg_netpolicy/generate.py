"""Generate DNS (Unbound), gateway (nftables) and proxy configuration from the CCC policy state.

    python -m xg_netpolicy.generate --state /var/lib/xephyguard/policy/state.json --out /var/lib/xephyguard/net
    python -m xg_netpolicy.generate --state ... --out ... --watch --apply     # sidecar mode

--apply runs `nft -f <out>/sets.nft` and `unbound-control -c $XG_UNBOUND_CONF reload` after every change, and
`conntrack -D -s <ip>` for PCs that newly joined test/isolated (all of them on start). sets.nft is
always applied on the first pass, and again whenever the live table's sets differ from it (checked
every --resync seconds, e.g. after a reboot or an nftables reload emptied them). Files are written
atomically; a broken state document never replaces a working configuration. In --watch mode an
error in one iteration (bad document, OSError, failed tool, bug) is logged and counted and the
loop keeps running with the previous configuration.
"""
from __future__ import annotations

import argparse
import hashlib
import ipaddress
import json
import logging
import os
import pathlib
import subprocess
import sys
import time

from .state import GROUPS, State

log = logging.getLogger("xg-netpolicy")


def unbound_conf(s: State) -> str:
    """Unbound views: one view per restrictive group; clients are mapped to views by IP.
    Domains of always-blocked categories (DoH resolvers) are blocked for every client."""
    out = [
        "# Generated by XephyGuard (xg_netpolicy). Do not edit; changes are overwritten.",
        f"# state version {s.version}",
        "server:",
        f"    access-control: {s.lab_subnet} allow",
        "    access-control: 127.0.0.0/8 allow",
    ]
    always = sorted(s.blocked_domains_for_group(None).domains)
    for d in always:
        out.append(f'    local-zone: "{d}." always_nxdomain')
    for g in ("test", "block_ai", "isolated"):
        for ip in sorted(s.groups.get(g, [])):
            out.append(f"    access-control-view: {ip}/32 xg_{g}")
    for g in ("test", "block_ai", "isolated"):
        out += ["", "view:", f'    name: "xg_{g}"', "    view-first: yes"]
        if g == "isolated":
            out.append('    local-zone: "." always_refuse')
            continue
        for d in sorted(s.blocked_domains_for_group(g).domains):
            out.append(f'    local-zone: "{d}." always_nxdomain')
    return "\n".join(out) + "\n"


def _set_elements(ips: list[str]) -> str:
    return ", ".join(sorted(set(ips))) if ips else ""


def nft_sets(s: State) -> str:
    """Element updates for the static table installed by ccc-deploy (proxy/nftables/xephyguard.nft)."""
    lines = [f"# Generated by XephyGuard, state version {s.version}"]
    for g in GROUPS:
        name = f"{g}_clients"
        lines.append(f"flush set inet xephyguard {name}")
        el = _set_elements(s.groups.get(g, []))
        if el:
            lines.append(f"add element inet xephyguard {name} {{ {el} }}")
    v4 = [ip for ip in s.doh_ips if isinstance(ipaddress.ip_network(ip, strict=False), ipaddress.IPv4Network)]
    v6 = [ip for ip in s.doh_ips if isinstance(ipaddress.ip_network(ip, strict=False), ipaddress.IPv6Network)]
    lines.append("flush set inet xephyguard resolver_ips")
    if v4:
        lines.append(f"add element inet xephyguard resolver_ips {{ {', '.join(v4)} }}")
    lines.append("flush set inet xephyguard resolver_ips6")
    if v6:
        lines.append(f"add element inet xephyguard resolver_ips6 {{ {', '.join(v6)} }}")
    return "\n".join(lines) + "\n"


def proxy_json(s: State) -> str:
    doc = {
        "version": s.version,
        "groups": s.groups,
        "categories": s.categories,
        "path_rules": s.path_rules,
        "group_categories": s.group_categories,
        "always_block": s.always_block,
        "google": s.google,
        "inspect_hosts": s.inspect_hosts,
        "log_urls": s.log_urls,
        "events_url": s.events_url,
        "events_token": s.events_token,
        "ccc_ip": s.ccc_ip,
        "lab_subnet": s.lab_subnet,
    }
    return json.dumps(doc, indent=1, sort_keys=True) + "\n"


def _write(path: pathlib.Path, text: str) -> bool:
    if path.exists() and path.read_text() == text:
        return False
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    os.chmod(tmp, 0o644)
    tmp.replace(path)
    return True


def generate(state_path: pathlib.Path, out: pathlib.Path) -> dict[str, bool]:
    return generate_state(State.load(state_path), out)


def generate_state(s: State, out: pathlib.Path) -> dict[str, bool]:
    out.mkdir(parents=True, exist_ok=True)
    return {
        "unbound": _write(out / "unbound-xephyguard.conf", unbound_conf(s)),
        "nft": _write(out / "sets.nft", nft_sets(s)),
        "proxy": _write(out / "proxy.json", proxy_json(s)),
    }


def _nft_table_present() -> bool:
    try:
        r = subprocess.run(["nft", "list", "table", "inet", "xephyguard"], capture_output=True, text=True)
        return r.returncode == 0
    except FileNotFoundError:
        return False


UNBOUND_CONF = "/etc/unbound/unbound.conf"


def restricted_ips(s: State) -> set[str]:
    """IPs in the nft sets whose forwarded traffic is dropped (test_clients, isolated_clients)."""
    return set(s.groups.get("test", [])) | set(s.groups.get("isolated", []))


def desired_sets(s: State) -> dict[str, list]:
    """The elements sets.nft puts into each set, as collapsed networks (comparable with live_sets)."""
    want = {f"{g}_clients": list(s.groups.get(g, [])) for g in GROUPS}
    nets = [ipaddress.ip_network(x, strict=False) for x in s.doh_ips]
    want["resolver_ips"] = [n for n in nets if n.version == 4]
    want["resolver_ips6"] = [n for n in nets if n.version == 6]
    return {k: _collapse(v) for k, v in want.items()}


def _collapse(items) -> list:
    nets = []
    for x in items:
        if isinstance(x, dict) and "range" in x:
            lo, hi = (ipaddress.ip_address(a) for a in x["range"])
            nets += ipaddress.summarize_address_range(lo, hi)
        elif isinstance(x, dict) and "prefix" in x:
            nets.append(ipaddress.ip_network(f'{x["prefix"]["addr"]}/{x["prefix"]["len"]}', strict=False))
        else:
            nets.append(ipaddress.ip_network(x, strict=False))
    out = []
    for v in (4, 6):
        out += ipaddress.collapse_addresses(n for n in nets if n.version == v)
    return out


def live_sets() -> dict[str, list] | None:
    """Elements of the sets in the running `table inet xephyguard`, or None when it can't be read
    (no nft, no table). Ranges/prefixes that nft merged are collapsed like desired_sets."""
    try:
        r = subprocess.run(["nft", "-j", "list", "table", "inet", "xephyguard"], capture_output=True, text=True)
        if r.returncode:
            return None
        doc = json.loads(r.stdout)
        sets = {}
        for obj in doc.get("nftables", []):
            st = obj.get("set") if isinstance(obj, dict) else None
            if st:
                # elements with counters/timeouts come wrapped as {"elem": {"val": ...}}
                el = [e["elem"]["val"] if isinstance(e, dict) and "elem" in e else e for e in st.get("elem", [])]
                sets[st["name"]] = _collapse(el)
        return sets
    except (FileNotFoundError, ValueError, KeyError, TypeError) as e:
        log.warning("could not read live nft sets: %s", e)
        return None


def sets_out_of_sync(s: State) -> bool:
    """True when the live table exists but its sets differ from sets.nft (I-PROXY-5)."""
    live = live_sets()
    if live is None:
        return False
    want = desired_sets(s)
    return any(live.get(k, []) != v for k, v in want.items())


def flush_conntrack(ips) -> None:
    """Delete tracked flows of PCs that just became test/isolated (I-PROXY-4), so a tunnel or a
    redirected flow opened before the change is not carried on by its conntrack/NAT entry."""
    for ip in sorted(ips):
        try:
            r = subprocess.run(["conntrack", "-D", "-s", ip], capture_output=True, text=True)
        except FileNotFoundError:
            log.warning("conntrack not installed; open flows of %d new restricted PC(s) not flushed", len(ips))
            return
        msg = (r.stderr or r.stdout or "").strip()
        # exit 1 with "0 flow entries have been deleted" only means the PC had nothing open
        if r.returncode and "0 flow entries" not in msg:
            log.error("conntrack -D -s %s failed: %s", ip, msg)
        else:
            log.info("conntrack flushed for %s", ip)


def apply(out: pathlib.Path, changed: dict[str, bool], network_mode: str | None = None,
          flush_ips: set[str] | frozenset[str] = frozenset()) -> None:
    """flush_ips: IPs newly in test/isolated; their conntrack entries are deleted once the sets
    are in place (never before, or the next packet would recreate them unrestricted)."""
    if changed.get("nft") or flush_ips:
        mode = (network_mode or os.environ.get("XG_NETWORK_MODE", "")).strip()
        if mode == "proxy_only" or not _nft_table_present():
            log.info("skipping nft sets reload (%s)",
                     "proxy_only mode" if mode == "proxy_only" else "table inet xephyguard unavailable")
        else:
            ok = True
            if changed.get("nft"):
                r = subprocess.run(["nft", "-f", str(out / "sets.nft")], capture_output=True, text=True)
                ok = not r.returncode
                if ok:
                    log.info("nftables sets updated")
                else:
                    log.error("nft failed: %s", r.stderr.strip())
            if ok and flush_ips:
                flush_conntrack(flush_ips)
    if changed.get("unbound"):
        # -c: the running config names the control socket (unix socket, I-PROXY-2)
        conf = os.environ.get("XG_UNBOUND_CONF") or UNBOUND_CONF
        r = subprocess.run(["unbound-control", "-c", conf, "reload"], capture_output=True, text=True)
        if r.returncode:
            log.error("unbound reload failed: %s", r.stderr.strip() or r.stdout.strip())
        else:
            log.info("unbound reloaded")


class InvalidState(Exception):
    """The state document can't be used (bad JSON, wrong types, failed validation)."""


def _load(path: pathlib.Path) -> tuple[State, str | None]:
    """Parse the state document and its raw network_mode. Any parse/validation error becomes
    InvalidState; OSError (file replaced or unreadable just now) is passed through for a retry."""
    try:
        s = State.load(path)
        raw_mode = json.loads(path.read_text()).get("network_mode")
        if raw_mode is not None and not isinstance(raw_mode, str):
            raise TypeError(f"network_mode must be a string, not {type(raw_mode).__name__}")
        return s, raw_mode
    except OSError:
        raise
    except Exception as e:  # ValueError, KeyError, TypeError, AttributeError from from_dict/validate
        raise InvalidState(f"{type(e).__name__}: {e}") from e


def _log_failure(consecutive: int, total: int, msg: str, exc: BaseException, trace: bool) -> None:
    # every failure is counted; a persistent one (e.g. read-only out dir) is logged on the 1st,
    # 2nd, 4th, 8th... consecutive attempt so the log stays readable
    if consecutive & (consecutive - 1) == 0:
        log.error("%s (failure %d, %d in a row), keeping previous configuration: %s",
                  msg, total, consecutive, exc, exc_info=exc if trace else None)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--state", required=True, type=pathlib.Path)
    ap.add_argument("--out", required=True, type=pathlib.Path)
    ap.add_argument("--watch", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--interval", type=float, default=1.0)
    ap.add_argument("--resync", type=float, default=10.0,
                    help="seconds between checks that the live nft sets still match sets.nft")
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    last = None
    restricted: set[str] | None = None  # None until the first apply: then every restricted IP is flushed
    applied: tuple[State, str | None] | None = None  # last applied state and its network_mode
    next_check = 0.0
    redo = False  # an earlier attempt for this digest failed half-way: rewrite/re-apply everything
    failures = consecutive = 0
    while True:
        digest = None
        try:
            digest = hashlib.sha256(a.state.read_bytes()).hexdigest() if a.state.exists() else None
            if digest and digest != last:
                s, raw_mode = _load(a.state)
                changed = generate_state(s, a.out)
                log.info("state %s -> %s", digest[:12], {k: v for k, v in changed.items() if v} or "no changes")
                if redo:
                    # files written before the failure compare equal now, but were never applied
                    changed = dict.fromkeys(changed, True)
                if a.apply:
                    now = restricted_ips(s)
                    if restricted is None:
                        # first pass: the files may predate this process (netpolicy-run.sh pre-generates
                        # them, or a reboot emptied the sets), so unchanged content proves nothing
                        changed["nft"] = True
                    apply(a.out, changed, network_mode=raw_mode,
                          flush_ips=now if restricted is None else now - restricted)
                    restricted = now
                    applied = (s, raw_mode)
                    next_check = time.monotonic() + a.resync
                last = digest
                redo = False
            elif applied and time.monotonic() >= next_check:
                next_check = time.monotonic() + a.resync
                s, raw_mode = applied
                mode = (raw_mode or os.environ.get("XG_NETWORK_MODE", "")).strip()
                if mode != "proxy_only" and sets_out_of_sync(s):
                    # table reloaded (xephyguard.nft deletes it) or sets edited by hand: flows opened
                    # meanwhile were unrestricted, so flush them all once the sets are back
                    log.warning("live nft sets differ from sets.nft, re-applying")
                    apply(a.out, {"nft": True}, network_mode=raw_mode, flush_ips=restricted_ips(s))
        except InvalidState as e:
            failures += 1
            consecutive += 1
            _log_failure(consecutive, failures, "invalid state document", e, trace=False)
            last = digest  # wait for the CCC to write a new document instead of re-parsing this one
        except Exception as e:
            # OSError (state replaced mid-read, out dir unwritable, a tool not runnable) or a bug:
            # the watcher must outlive it (I-PROXY-6); the same digest is retried next iteration
            failures += 1
            consecutive += 1
            _log_failure(consecutive, failures, "watch iteration failed", e, trace=True)
            if digest and digest != last:
                redo = True
        else:
            if consecutive:
                log.info("recovered after %d failed iteration(s)", consecutive)
            consecutive = 0
        if not a.watch:
            return 1 if consecutive else 0
        time.sleep(a.interval)

if __name__ == "__main__":
    sys.exit(main())
